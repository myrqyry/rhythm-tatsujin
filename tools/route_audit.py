#!/usr/bin/env python3
"""Audit the live FastAPI surface and reject stale Flask-era runtime wiring."""

from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FASTAPI_FILE = ROOT / "web" / "server_fastapi.py"
OUT_FILE = ROOT / "docs" / "flask-migration-status.md"

REQUIRED_ROUTES = {
    ("GET", "/api/status"),
    ("POST", "/api/upload-audio"),
    ("POST", "/api/generate-chart"),
    ("GET", "/api/tasks"),
    ("GET", "/api/charts"),
    ("GET", "/api/download-chart"),
    ("POST", "/api/start-training"),
    ("POST", "/api/stop-training"),
}

STALE_PATTERNS = {
    r"\bfrom\s+web\.server\b": "imports removed web.server",
    r"\bimport\s+web\.server\b": "imports removed web.server",
    r"\bfrom\s+train_transformer\b": "imports removed root train_transformer",
    r"\bFlask\s*\(": "constructs a Flask app",
    r"@app\.route\s*\(": "declares a Flask-style route",
}


def extract_routes(path: Path) -> list[tuple[str, str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    routes: list[tuple[str, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
                continue
            owner = decorator.func.value
            if not isinstance(owner, ast.Name) or owner.id != "app":
                continue
            method = decorator.func.attr.upper()
            if method not in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                continue
            if not decorator.args or not isinstance(decorator.args[0], ast.Constant):
                continue
            route = decorator.args[0].value
            if isinstance(route, str):
                routes.append((method, route))
    return sorted(routes, key=lambda item: (item[1], item[0]))


def stale_runtime_references() -> list[str]:
    issues: list[str] = []
    for path in (ROOT / "web").rglob("*.py"):
        source = path.read_text(encoding="utf-8")
        for pattern, description in STALE_PATTERNS.items():
            if re.search(pattern, source):
                issues.append(f"{path.relative_to(ROOT)}: {description}")
    return issues


def main() -> None:
    routes = extract_routes(FASTAPI_FILE)
    route_set = set(routes)
    issues = stale_runtime_references()

    missing = sorted(REQUIRED_ROUTES - route_set)
    for method, route in missing:
        issues.append(f"missing required route: {method} {route}")

    seen: set[tuple[str, str]] = set()
    for route in routes:
        if route in seen:
            issues.append(f"duplicate route: {route[0]} {route[1]}")
        seen.add(route)

    lines = [
        "# Flask → FastAPI Migration Status",
        "",
        "_Auto-generated by tools/route_audit.py; this file reflects inspected code, not a hard-coded success message._",
        "",
        f"FastAPI routes discovered: **{len(routes)}**.",
        "",
        "## Runtime migration checks",
        "",
    ]
    if issues:
        lines += [f"- ❌ {issue}" for issue in issues]
    else:
        lines += [
            "- ✅ No stale web.server, root train_transformer, Flask constructor, or app.route references under web/.",
            "- ✅ All required upload, generation, task, chart, download, and training routes are present.",
            "- ✅ No duplicate method/path route declarations were found.",
        ]

    lines += ["", "## FastAPI route inventory", ""]
    lines += [f"- {method} {route}" for method, route in routes]
    lines.append("")

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")

    if issues:
        raise SystemExit("Route audit failed:\n- " + "\n- ".join(issues))


if __name__ == "__main__":
    main()
